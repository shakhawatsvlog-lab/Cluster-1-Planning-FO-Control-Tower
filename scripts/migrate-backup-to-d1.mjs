#!/usr/bin/env node
/**
 * Converts a downloaded Control Tower JSON backup (`/api/admin/backup`)
 * or an existing `data/workspace-state.json` file into a D1 SQLite seed script.
 *
 * Usage:
 *   node scripts/migrate-backup-to-d1.mjs path/to/backup.json [--out cloudflare/seed-from-backup.sql] [--admin-password "YourPassword"]
 */

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

function parseArgs(argv) {
  const args = { input: '', out: 'cloudflare/seed-from-backup.sql', adminPassword: '' };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--out' && argv[i + 1]) {
      args.out = argv[++i];
    } else if (a.startsWith('--out=')) {
      args.out = a.slice('--out='.length);
    } else if (a === '--admin-password' && argv[i + 1]) {
      args.adminPassword = argv[++i];
    } else if (a.startsWith('--admin-password=')) {
      args.adminPassword = a.slice('--admin-password='.length);
    } else if (!a.startsWith('--') && !args.input) {
      args.input = a;
    }
  }
  return args;
}

function sqlEscapeString(str) {
  return `'${String(str).replace(/'/g, "''")}'`;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.input) {
    console.error(
      'Usage: node scripts/migrate-backup-to-d1.mjs <backup.json | data/workspace-state.json> [--out cloudflare/seed-from-backup.sql] [--admin-password "YourPassword"]'
    );
    process.exit(1);
  }

  const inputPath = path.resolve(process.cwd(), args.input);
  if (!fs.existsSync(inputPath)) {
    console.error(`Input file not found: ${inputPath}`);
    process.exit(1);
  }

  const raw = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
  if (!raw || !raw.meta || !Array.isArray(raw.records) || raw.records.length === 0) {
    console.error('Invalid backup JSON: expected { meta, records: [...] }');
    process.exit(1);
  }

  let adminAuth = raw.adminAuth && raw.adminAuth.passwordHash && raw.adminAuth.passwordSalt
    ? raw.adminAuth
    : null;

  if (args.adminPassword) {
    if (args.adminPassword.trim().length < 8) {
      console.error('--admin-password must be at least 8 characters long.');
      process.exit(1);
    }
    const salt = crypto.randomBytes(16).toString('hex');
    const hash = crypto.scryptSync(args.adminPassword.trim(), salt, 64).toString('hex');
    adminAuth = {
      passwordHash: hash,
      passwordSalt: salt,
      updatedAtIso: new Date().toISOString(),
    };
  }

  const normalizedDoc = {
    meta: raw.meta,
    records: raw.records,
    cuttingEntries: Array.isArray(raw.cuttingEntries) ? raw.cuttingEntries : [],
    referenceDateIso: raw.referenceDateIso || new Date().toISOString().slice(0, 10),
    hasCustomEdits: raw.hasCustomEdits !== undefined ? Boolean(raw.hasCustomEdits) : true,
    updatedAtIso: raw.updatedAtIso || new Date().toISOString(),
    reminders: raw.reminders || {
      recipients: [],
      schedule: {
        enabled: false,
        dailySendTime: '08:30',
        timezone: 'Africa/Cairo',
        alertScope: 'urgent_and_due_soon',
        customMessage: '',
        lastSentDateLocal: null,
        lastAttemptIso: null,
      },
      logs: [],
    },
    smtpConfig: raw.smtpConfig ?? null,
    siteConfig: raw.siteConfig || {
      companyName: 'Alex Apparels',
      portalTitle: 'Cluster 1 Planning & FO Control Tower',
      readOnlyPublicMode: true,
      recoveryEmail: '',
      inputStartOffsetDays: 10,
      upcomingFoOffsetDays: 15,
      cuttingAlertDays: 10,
    },
    cuttingSheetSync: raw.cuttingSheetSync || {
      enabled: false,
      sheetUrl: '',
      factoryUrls: {},
      outputSheetUrl: '',
      outputFactoryUrls: {},
      packingSheetUrl: '',
      packingFactoryUrls: {},
      syncMode: 'auto',
      intervalMinutes: 5,
      lastCheckedAtIso: null,
      lastUpdatedAtIso: null,
      lastStatus: 'Idle',
      lastMessage: 'Not connected yet.',
      lastMatchedCount: 0,
      lastUnmatchedCount: 0,
      lastTotalQty: 0,
      lastOutputMatchedCount: 0,
      lastOutputTotalQty: 0,
      lastPackingMatchedCount: 0,
      lastPackingTotalQty: 0,
      lastContentHash: '',
      factoryStatuses: {},
      logs: [],
    },
    adminAuth,
  };

  const outPath = path.resolve(process.cwd(), args.out);
  fs.mkdirSync(path.dirname(outPath), { recursive: true });

  const sql = [
    '-- Generated by scripts/migrate-backup-to-d1.mjs',
    '-- Execute against Cloudflare D1:',
    '--   npx wrangler d1 execute alex-control-tower-db --remote --file=' + args.out,
    '',
    'INSERT INTO workspace_state (id, data_json, updated_at)',
    `VALUES ('primary', ${sqlEscapeString(JSON.stringify(normalizedDoc))}, ${sqlEscapeString(normalizedDoc.updatedAtIso)})`,
    'ON CONFLICT(id) DO UPDATE SET',
    '  data_json = excluded.data_json,',
    '  updated_at = excluded.updated_at;',
    '',
  ].join('\n');

  fs.writeFileSync(outPath, sql, 'utf8');
  console.log(
    `Wrote D1 migration SQL (${normalizedDoc.records.length} planning records, ${normalizedDoc.cuttingEntries.length} cutting entries, adminAuth=${adminAuth ? 'present' : 'not set -> use initial setup or --admin-password'}) to ${args.out}`
  );
}

main();
